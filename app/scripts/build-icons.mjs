// Builds src/components/icons/icons.generated.ts: only the Lucide icons the app uses,
// as plain SVG node data drawn by <Icon> with react-native-svg (no icon font, works the
// same on iOS and in the web preview). Add a name to ICONS and run `npm run build:icons`.
// Lucide is ISC-licensed: https://lucide.dev/license
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ICONS = [
  'arrow-down-right', 'arrow-right', 'arrow-up', 'arrow-up-right', 'asterisk', 'badge-check', 'book-open',
  'camera', 'chart-column', 'check', 'chevron-left', 'chevron-right', 'circle-check', 'circle-dashed',
  'circle-minus', 'circle-user', 'circle-x', 'eye', 'flag', 'flame', 'flashlight', 'flashlight-off', 'house',
  'images', 'lightbulb', 'list-filter', 'message-circle-question-mark', 'minus', 'pencil', 'play',
  'refresh-cw', 'repeat', 'rotate-ccw', 'scan', 'scan-line', 'scan-text', 'smartphone', 'sparkles',
  'square-pen', 'star', 'sun', 'timer', 'trash', 'triangle-alert', 'trophy', 'wifi', 'x',
  // Accounts, timer, leaderboard, badges
  'at-sign', 'award', 'bell', 'bell-off', 'calendar', 'chevron-down', 'chevron-up', 'clipboard-check', 'clock',
  'coffee', 'crown', 'eye-off', 'graduation-cap', 'key-round', 'layers', 'library', 'lock', 'log-out', 'medal',
  'moon', 'pause', 'plus', 'settings', 'skip-forward', 'square', 'sunrise', 'target', 'ticket', 'user-round',
  'users', 'volume-2', 'volume-x',
  // Multiple choice, assistant chat
  'circle-question-mark', 'send', 'message-circle', 'heart', 'hand',
  // Answer dock, polish
  'text-align-start',
  // Fosfor redesign (design spec 3.1)
  'highlighter', 'sticky-note', 'notebook-pen', 'pen-line', 'shirt', 'glasses', 'headphones', 'party-popper',
  'calendar-days', 'list-checks', 'chart-spline', 'trending-up', 'trending-down', 'circle-dot', 'vibrate',
  'message-circle-more', 'image', 'hourglass', 'chevrons-up',
];

const require = createRequire(import.meta.url);
const appRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const iconsDir = path.join(path.dirname(require.resolve('lucide/package.json')), 'dist', 'esm', 'icons');

const entries = [];
for (const name of [...ICONS].sort()) {
  const mod = await import(pathToFileURL(path.join(iconsDir, `${name}.mjs`)).href);
  const node = mod.default.map(([tag, attrs]) => {
    const { key, ...rest } = attrs;
    return [tag, rest];
  });
  entries.push(`  '${name}': ${JSON.stringify(node)},`);
}

const out = path.join(appRoot, 'src', 'components', 'icons', 'icons.generated.ts');
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(
  out,
  `// GENERATED by scripts/build-icons.mjs — do not edit. Icons from Lucide (ISC license).\n` +
    `export type IconNode = readonly (readonly [string, Readonly<Record<string, string | number>>])[];\n\n` +
    `export const ICONS = {\n${entries.join('\n')}\n} as const satisfies Record<string, IconNode>;\n\n` +
    `export type IconName = keyof typeof ICONS;\n`,
);
console.log(`Wrote ${path.relative(appRoot, out)} (${ICONS.length} icons)`);
